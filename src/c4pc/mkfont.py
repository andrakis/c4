# mkfont.py -- the display's faces for c4pc (gui.c, font.c), as C tables.
#
#   python3 -I src/c4pc/mkfont.py OUT.c FONT.ttf...
#
# libjs's page draws TEXT and TEXT2 in the browser's fonts (display.js
# FONTS); a bare PC has none, so c4pc carries outlines of its own: each
# face's glyphs for the characters 0-255 (Latin-1, as TEXT2's bytes are),
# their quadratic curves flattened here into line segments in font units,
# which font.c scales to any size and fills with coverage (anti-aliased).
# The faces are free ones (Liberation: SIL OFL 1.1; DejaVu: the Bitstream
# Vera licence), read from the system's fonts at build time; each one's
# copyright and licence lines go into OUT.c beside its data.
import sys, math
from fontTools.ttLib import TTFont

out, files = sys.argv[1], sys.argv[2:]

def flatten(pts, on):
    """a closed quadratic contour as a polygon: (x, y) in font units"""
    n = len(pts)
    if n == 0:
        return []
    # start at an on-curve point (or the midpoint of two off-curve ones)
    k0 = next((i for i in range(n) if on[i]), None)
    if k0 is None:
        a, b = pts[0], pts[1 % n]
        seq = [((a[0] + b[0]) / 2, (a[1] + b[1]) / 2, True)] + [(p[0], p[1], False) for p in pts[1:] + pts[:1]]
    else:
        seq = [(pts[(k0 + i) % n][0], pts[(k0 + i) % n][1], on[(k0 + i) % n]) for i in range(n)]
    # the implied on-curve points between two off-curve ones
    full = []
    for i, p in enumerate(seq):
        q = seq[(i + 1) % len(seq)]
        full.append(p)
        if not p[2] and not q[2]:
            full.append(((p[0] + q[0]) / 2, (p[1] + q[1]) / 2, True))
    poly = []
    cur = full[0]
    poly.append((cur[0], cur[1]))
    i = 1
    m = len(full)
    while i <= m:
        p = full[i % m]
        if p[2]:
            poly.append((p[0], p[1])); cur = p; i += 1
        else:
            e = full[(i + 1) % m]
            # segments by the curve's size: finer for a long one
            d = math.hypot(p[0] - cur[0], p[1] - cur[1]) + math.hypot(e[0] - p[0], e[1] - p[1])
            steps = max(2, min(12, int(d / 120) + 2))
            for s in range(1, steps + 1):
                t = s / steps
                x = (1 - t) ** 2 * cur[0] + 2 * (1 - t) * t * p[0] + t * t * e[0]
                y = (1 - t) ** 2 * cur[1] + 2 * (1 - t) * t * p[1] + t * t * e[1]
                poly.append((x, y))
            cur = e; i += 2
    if len(poly) > 1 and poly[-1] == poly[0]:
        poly.pop()
    return [(int(round(x)), int(round(y))) for x, y in poly]

lines = ['/* generated by src/c4pc/mkfont.py: do not edit */', '#include "c4pc.h"', '#include "font.h"', '']
faces = []
for fi, path in enumerate(files):
    f = TTFont(path)
    name = f['name']
    notice = [name.getDebugName(0) or '', name.getDebugName(13) or '']
    lines.append('/* %s: %s */' % (path.split('/')[-1], ' '.join(x.replace('*/', '* /') for x in notice if x)[:600]))
    upem = f['head'].unitsPerEm
    asc, desc = f['hhea'].ascent, f['hhea'].descent
    cmap = f.getBestCmap()
    glyf = f['glyf']
    hmtx = f['hmtx']
    gs = f.getGlyphSet()
    adv, start, ncont, pts, cnt = [], [], [], [], []
    for ch in range(256):
        g = cmap.get(ch)
        if g is None:
            g = cmap.get(0x3f) if ch >= 0x20 and ch not in (0x7f,) and not (0x80 <= ch < 0xa0) else None
        if g is None:
            adv.append(0); start.append(len(cnt)); ncont.append(0)
            continue
        adv.append(hmtx[g][0])
        start.append(len(cnt))
        coords, ends, flags = glyf[g].getCoordinates(glyf)
        k = 0
        n = 0
        for e in ends:
            c = [tuple(coords[j]) for j in range(k, e + 1)]
            o = [bool(flags[j] & 1) for j in range(k, e + 1)]
            k = e + 1
            poly = flatten(c, o)
            if len(poly) >= 2:
                cnt.append(len(poly))
                pts.extend(poly)
                n += 1
        ncont.append(n)
    cstart = []
    acc = 0
    for c in cnt:
        cstart.append(acc); acc += c
    p = 'f%d' % fi
    lines.append('static const u16 %s_adv[256] = {%s};' % (p, ','.join(map(str, adv))))
    lines.append('static const u16 %s_first[256] = {%s};' % (p, ','.join(map(str, start))))
    lines.append('static const u8 %s_ncont[256] = {%s};' % (p, ','.join(map(str, ncont))))
    lines.append('static const u16 %s_cnt[%d] = {%s};' % (p, max(1, len(cnt)), ','.join(map(str, cnt)) or '0'))
    lines.append('static const u32 %s_cstart[%d] = {%s};' % (p, max(1, len(cstart)), ','.join(map(str, cstart)) or '0'))
    flat = []
    for x, y in pts:
        flat += [x, y]
    lines.append('static const i16 %s_pts[%d] = {%s};' % (p, max(1, len(flat)), ','.join(map(str, flat)) or '0'))
    lines.append('')
    faces.append('  {%d, %d, %d, %s_adv, %s_first, %s_ncont, %s_cnt, %s_cstart, %s_pts}' % (upem, asc, desc, p, p, p, p, p, p))
lines.append('const font_face font_faces[%d] = {\n%s\n};' % (len(faces), ',\n'.join(faces)))
lines.append('const int font_nfaces = %d;' % len(faces))
open(out, 'w').write('\n'.join(lines) + '\n')
